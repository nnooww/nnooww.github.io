const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');

const temp = fs.mkdtempSync(path.join(os.tmpdir(), 'class-questions-'));
process.env.DB_FILE = path.join(temp, 'test.sqlite');
const { server, db } = require('./server');

test('회원가입 역할 분리와 학생 질문 흐름', async t => {
  await new Promise(resolve => server.listen(0, '127.0.0.1', resolve));
  t.after(async () => {
    await new Promise(resolve => server.close(resolve));
    db.close(); fs.rmSync(temp, { recursive: true, force: true });
  });
  const base = `http://127.0.0.1:${server.address().port}`;
  const call = async (route, { method = 'GET', body, cookie, origin } = {}) => {
    const headers = { 'Content-Type': 'application/json' };
    if (cookie) headers.Cookie = cookie;
    if (origin) headers.Origin = origin;
    const response = await fetch(base + route, { method, headers, body: body === undefined ? undefined : JSON.stringify(body) });
    return { status: response.status, data: await response.json(), cookie: response.headers.get('set-cookie')?.split(';')[0] };
  };
  const signup = (name, role, extra = {}) => call('/api/signup', { method: 'POST', body: { displayName: name, role, password: 'studentPass123', ...extra } });

  assert.deepEqual((await call('/api/signup-options')).data, { teacherAvailable: true });
  assert.equal((await signup('invalid', 'admin')).status, 400);
  assert.equal((await signup('', 'student')).status, 400);
  assert.equal((await signup('weak', 'student', { password: '123' })).status, 400);
  assert.equal((await signup('weak teacher', 'teacher', { password: '123' })).status, 400);
  const teacherSignup = await signup('선생님', 'teacher', { password: 'safePassword123' });
  assert.equal(teacherSignup.status, 200);
  assert.equal(teacherSignup.data.user.role, 'teacher');
  assert.match(teacherSignup.data.user.username, /^teacher_[0-9a-f]{20}$/);
  assert.deepEqual((await call('/api/signup-options')).data, { teacherAvailable: false });
  assert.equal((await signup('second teacher', 'teacher')).status, 409);
  assert.equal((await signup('선생님', 'student')).status, 409);
  assert.throws(() => db.prepare('INSERT INTO users(username,display_name,role,password_salt,password_hash,created_at) VALUES(?,?,?,?,?,?)')
    .run('teacher2', '두 번째 선생님', 'teacher', 'test-salt', 'test-hash', Date.now()));
  const teacher = await call('/api/login', { method: 'POST', body: { username: '선생님', password: 'safePassword123' } });
  assert.equal(teacher.status, 200);
  assert.equal(teacher.data.user.role, 'teacher');
  db.prepare('UPDATE users SET username = ? WHERE id = ?').run('teacher', teacher.data.user.id);
  assert.equal((await call('/api/login', { method: 'POST', body: { username: 'teacher', password: 'safePassword123' } })).status, 200);
  assert.equal((await call('/api/admin/database')).status, 401);
  const alice = await signup('alice1', 'student');
  const bob = await signup('bob_22', 'student');
  assert.equal(alice.status, 200);
  assert.equal(alice.data.user.needsPasswordSetup, false);
  assert.match(alice.data.user.username, /^student_[0-9a-f]{20}$/);
  assert.notEqual(alice.data.user.username, bob.data.user.username);
  assert.equal((await signup('alice1', 'student')).status, 409);
  assert.equal((await call('/api/login', { method: 'POST', body: { username: 'alice1', password: 'studentPass123' } })).data.user.role, 'student');
  assert.equal((await call('/api/me', { cookie: alice.cookie })).data.user.displayName, 'alice1');
  assert.equal((await call('/api/queue')).status, 401);
  assert.equal((await call('/api/questions', { method: 'POST', body: { title: '교사 질문' }, cookie: teacher.cookie })).status, 403);
  assert.equal((await call('/api/questions', { method: 'POST', body: { title: '잘못된 출처' }, cookie: alice.cookie, origin: 'https://other.example' })).status, 403);

  const first = await call('/api/questions', { method: 'POST', body: { title: 'Python 오류', detail: '모듈을 못 찾음' }, cookie: alice.cookie });
  assert.equal(first.status, 201);
  assert.equal((await call('/api/questions', { method: 'POST', body: { title: '중복', detail: '중복 질문' }, cookie: alice.cookie })).status, 409);
  assert.equal((await call('/api/questions', { method: 'POST', body: { title: 'DB 오류' }, cookie: bob.cookie })).status, 400);
  assert.equal((await call('/api/questions', { method: 'POST', body: { title: 'DB 오류', detail: '  ' }, cookie: bob.cookie })).status, 400);
  const second = await call('/api/questions', { method: 'POST', body: { title: 'DB 오류', detail: '연결이 안 됨' }, cookie: bob.cookie });
  assert.equal(second.status, 201);
  assert.equal((await call('/api/admin/overview', { cookie: alice.cookie })).status, 403);
  assert.equal((await call('/api/admin/database', { cookie: alice.cookie })).status, 403);
  const overview = await call('/api/admin/overview', { cookie: teacher.cookie });
  assert.equal(overview.status, 200);
  assert.deepEqual(overview.data.questions.map(q => q.title), ['Python 오류', 'DB 오류']);
  assert.equal(JSON.stringify(overview.data).includes('password_hash'), false);
  assert.equal((await call(`/api/admin/questions/${first.data.question.id}`, { method: 'PATCH', cookie: teacher.cookie, body: { status: 'resolved' } })).status, 404);
  const queue = await call('/api/queue', { cookie: alice.cookie });
  assert.deepEqual(queue.data, { count: 2, position: 1 });
  assert.deepEqual((await call('/api/queue', { cookie: bob.cookie })).data, { count: 2, position: 2 });
  assert.deepEqual((await call('/api/questions', { cookie: alice.cookie })).data.questions.map(q => q.title), ['Python 오류']);
  assert.deepEqual((await call('/api/questions', { cookie: bob.cookie })).data.questions.map(q => q.title), ['DB 오류']);
  assert.equal((await call('/api/questions', { cookie: teacher.cookie })).status, 403);
  assert.equal((await call(`/api/questions/${first.data.question.id}`, { method: 'DELETE', cookie: bob.cookie })).status, 403);
  assert.equal((await call(`/api/questions/${first.data.question.id}`, { method: 'DELETE', cookie: alice.cookie })).status, 200);
  assert.deepEqual((await call('/api/queue', { cookie: bob.cookie })).data, { count: 1, position: 1 });
  assert.equal((await call('/api/questions', { cookie: bob.cookie })).data.questions[0].status, 'waiting');
  assert.equal((await call(`/api/admin/questions/${second.data.question.id}/answer`, { method: 'POST', cookie: bob.cookie, body: { answer: '학생 답변 시도' } })).status, 403);
  assert.equal((await call(`/api/admin/questions/${second.data.question.id}/answer`, { method: 'POST', cookie: teacher.cookie, body: { answer: '  ' } })).status, 400);
  assert.equal((await call(`/api/admin/questions/${second.data.question.id}/answer`, { method: 'POST', cookie: teacher.cookie, body: { answer: '연결 문자열을 확인하세요.' } })).status, 200);
  assert.equal((await call('/api/questions', { cookie: bob.cookie })).data.questions[0].answer, '연결 문자열을 확인하세요.');
  assert.equal((await call('/api/questions', { cookie: bob.cookie })).data.questions[0].status, 'resolved');
  const databaseView = await call('/api/admin/database', { cookie: teacher.cookie });
  assert.equal(databaseView.status, 200);
  assert.deepEqual(databaseView.data.users.map(account => [account.displayName, account.role]),
    [['선생님', 'teacher'], ['alice1', 'student'], ['bob_22', 'student']]);
  assert.deepEqual(databaseView.data.questions.map(item => [item.title, item.status]), [['DB 오류', 'resolved']]);
  assert.equal(databaseView.data.questions[0].studentName, 'bob_22');
  assert.equal(databaseView.data.questions[0].answer, '연결 문자열을 확인하세요.');
  assert.equal(/password|salt|hash|session|token/i.test(JSON.stringify(databaseView.data)), false);
  assert.deepEqual((await call('/api/admin/overview', { cookie: teacher.cookie })).data.questions, []);
  assert.deepEqual((await call('/api/queue', { cookie: teacher.cookie })).data, { count: 0, position: 0 });
  assert.equal((await call(`/api/admin/questions/${second.data.question.id}/answer`, { method: 'POST', cookie: teacher.cookie, body: { answer: '다시 답변' } })).status, 404);
  assert.equal((await call('/api/logout', { method: 'POST', cookie: alice.cookie })).status, 200);
  assert.equal((await call('/api/me', { cookie: alice.cookie })).status, 401);
  const aliceAgain = await call('/api/login', { method: 'POST', body: { username: 'alice1', password: 'studentPass123' } });
  assert.equal(aliceAgain.status, 200);
  db.prepare("UPDATE users SET password_set = 0 WHERE display_name = 'alice1'").run();
  assert.equal((await call('/api/me', { cookie: aliceAgain.cookie })).data.user.needsPasswordSetup, true);
  assert.equal((await call('/api/me/password', { method: 'POST', cookie: aliceAgain.cookie, body: { password: 'short' } })).status, 400);
  assert.equal((await call('/api/me/password', { method: 'POST', cookie: teacher.cookie, body: { password: 'newPassword123' } })).status, 403);
  assert.equal((await call('/api/me/password', { method: 'POST', cookie: aliceAgain.cookie, body: { password: 'newPassword123' } })).data.user.needsPasswordSetup, false);
  assert.equal((await call('/api/login', { method: 'POST', body: { username: 'alice1', password: 'studentPass123' } })).status, 401);
  assert.equal((await call('/api/login', { method: 'POST', body: { username: 'alice1', password: 'newPassword123' } })).status, 200);
  assert.equal((await call('/api/login', { method: 'POST', body: { username: 'teacher', password: 'wrong' } })).status, 401);
  assert.ok(fs.existsSync(process.env.DB_FILE));
});
